const big = (text) => text[0].toUpperCase() + text.slice(1);

/** 1st, 2nd, 3rd, 4th … 11th, 12th, 13th, 21st (for dates in the stories). */
const ord = (x) => {
  const n = Number(x);
  const end = n % 100 >= 11 && n % 100 <= 13 ? "th" : { 1: "st", 2: "nd", 3: "rd" }[n % 10] ?? "th";
  return `${x}${end}`;
};

